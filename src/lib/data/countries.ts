export const countries: Country[] = [...popularCountries, ...otherCountries];
export const defaultCountry = popularCountries[0]; // India: fallback when a stored number's prefix can't be recognized

// When two countries share a dial code (e.g. +7), these win when a stored number is split.
const PRIMARY_ISO = new Set<string>(["RU","MA","NO","RE","GP","CW"]);

// Split a stored E.164 number ("+919876543210") back into country + local part.
// Longest dial code wins; on a tie, popular / primary countries win. Returns country: null
// when there is no existing value, so new entries start with nothing pre-selected.
export function parseStoredPhone(phone?: string | null): {
  country: Country | null;
  local: string;
} {
  if (!phone) return { country: null, local: "" };
  const candidates = countries.filter((c) => phone.startsWith(c.dialCode));
  if (candidates.length === 0) return { country: defaultCountry, local: phone.replace(/\D/g, "") };
  const rank = (c: Country) => (c.popular || PRIMARY_ISO.has(c.iso) ? 1 : 0);
  const match = candidates.reduce((best, c) => {
    if (c.dialCode.length !== best.dialCode.length) return c.dialCode.length > best.dialCode.length ? c : best;
    return rank(c) > rank(best) ? c : best;
  });
  return { country: match, local: phone.slice(match.dialCode.length) };
}
